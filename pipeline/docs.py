"""Generate docs/data_catalog.md from the warehouse, the models and schema.yml.

The catalog is plain Markdown so it renders on GitHub without a docs server:
sources with their raw column labels (English and Arabic, from the portal
metadata), a lineage graph in Mermaid, and one section per model with its
columns, types, row count and tests.
"""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import date
from pathlib import Path

from pipeline.config import Catalogue, Settings
from pipeline.extract import Manifest
from pipeline.quality import load_schema
from pipeline.transform import LAYERS, Model, discover, execution_order
from pipeline.warehouse import connect, table_columns


class DocsError(RuntimeError):
    """The warehouse has not been built yet."""


def _escape(text: object) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _node_id(relation: str) -> str:
    return relation.replace(".", "_")


def lineage_mermaid(models: dict[str, Model]) -> str:
    """A left-to-right flowchart: sources and seeds, then each model layer."""
    sources = sorted({s for m in models.values() for s in m.sources})
    seeds = sorted({f"seeds.{s}" for m in models.values() for s in m.seeds})
    lines = ["flowchart LR"]

    def subgraph(title: str, relations: list[str]) -> None:
        lines.append(f"  subgraph {title.lower()}[{title}]")
        for relation in relations:
            lines.append(f"    {_node_id(relation)}[{relation.split('.', 1)[1]}]")
        lines.append("  end")

    subgraph("Sources", sources)
    subgraph("Seeds", seeds)
    for layer in LAYERS:
        names = sorted(m.relation for m in models.values() if m.layer == layer)
        if names:
            subgraph(layer.capitalize(), names)

    for name in execution_order(models):
        model = models[name]
        target = _node_id(model.relation)
        upstream = [*model.sources, *(f"seeds.{s}" for s in model.seeds)]
        upstream += [models[r].relation for r in model.refs]
        for relation in upstream:
            lines.append(f"  {_node_id(relation)} --> {target}")
    return "\n".join(lines)


def _test_labels(entry: dict) -> tuple[list[str], dict[str, list[str]]]:
    def label(spec) -> str:
        if isinstance(spec, str):
            return spec
        kind, args = next(iter(spec.items()))
        if kind in {"expression", "query"}:
            return f"{kind}: {args['name']}"
        if kind == "unique" and isinstance(args, list):
            return f"unique ({', '.join(args)})"
        if kind == "freshness":
            return f"freshness ({args['column']})"
        return kind

    model_tests = [label(s) for s in entry.get("tests", [])]
    column_tests: dict[str, list[str]] = defaultdict(list)
    for column in entry.get("columns", []):
        column_tests[column["name"]].extend(label(s) for s in column.get("tests", []))
    return model_tests, column_tests


def render_catalog(settings: Settings, catalogue: Catalogue, today: date | None = None) -> str:
    if not settings.warehouse_path.exists():
        raise DocsError("no warehouse yet, run `python -m pipeline run` first")
    models = discover(settings.models_dir)
    schema = {m["name"]: m for m in load_schema(settings.schema_file).get("models", [])}
    manifest = Manifest(settings.manifest_path)
    portal = catalogue.portal

    out: list[str] = [
        "# Data catalog",
        "",
        f"Generated by `python -m pipeline docs` on {(today or date.today()).isoformat()}. "
        "Do not edit by hand.",
        "",
        f"Source data: [Qatar Open Data Portal]({portal.site_url}), "
        f"licensed [{portal.licence}]({portal.licence_url}).",
        "",
        "## Sources",
        "",
        "| Key | Dataset | Publisher | Rows | Fetched (UTC) |",
        "| --- | --- | --- | ---: | --- |",
    ]
    for source in catalogue.sources:
        entry = manifest.get(source.key)
        rows = entry.row_count if entry else ""
        fetched = entry.fetched_at[:16].replace("T", " ") if entry else "not fetched"
        out.append(
            f"| `{source.key}` | [{_escape(source.title)}]({source.page_url(portal)}) "
            f"| {_escape(source.publisher)} | {rows} | {fetched} |"
        )

    out += ["", "### Raw column labels", ""]
    out.append(
        "The portal derives some column names from Arabic labels (`lmw_shr`, `ljns`...). "
        "These are the labels it publishes for each raw column."
    )
    for source in catalogue.sources:
        meta_path = settings.raw_dir / f"{source.key}.meta.json"
        if not meta_path.exists():
            continue
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        out += [
            "",
            f"**{source.key}**",
            "",
            "| Column | Type | Label (EN) | Label (AR) |",
            "| --- | --- | --- | --- |",
        ]
        for f in meta.get("fields", []):
            out.append(
                f"| `{f['name']}` | {f['type']} | {_escape(f['label_en'])} "
                f"| {_escape(f['label_ar'])} |"
            )

    out += ["", "## Lineage", "", "```mermaid", lineage_mermaid(models), "```", ""]

    con = connect(settings.warehouse_path, read_only=True)
    try:
        for layer in LAYERS:
            layer_models = sorted(
                (m for m in models.values() if m.layer == layer), key=lambda m: m.name
            )
            if not layer_models:
                continue
            out += [f"## {layer.capitalize()}", ""]
            for model in layer_models:
                entry = schema.get(model.name, {})
                model_tests, column_tests = _test_labels(entry)
                descriptions = {
                    c["name"]: c.get("description", "") for c in entry.get("columns", [])
                }
                rows = con.execute(f"select count(*) from {model.relation}").fetchone()[0]
                out += [
                    f"### {model.relation}",
                    "",
                    model.description or entry.get("description", ""),
                    "",
                    f"{model.materialized}, {rows} rows. Defined in "
                    f"[`{model.path.relative_to(settings.root).as_posix()}`]"
                    f"(../{model.path.relative_to(settings.root).as_posix()}).",
                    "",
                ]
                if model_tests:
                    out += ["Table tests: " + ", ".join(f"`{t}`" for t in model_tests), ""]
                out += ["| Column | Type | Description | Tests |", "| --- | --- | --- | --- |"]
                for column, dtype in table_columns(con, model.layer, model.name):
                    tests = ", ".join(column_tests.get(column, []))
                    out.append(
                        f"| `{column}` | {dtype} | {_escape(descriptions.get(column, ''))} "
                        f"| {tests} |"
                    )
                out.append("")
    finally:
        con.close()
    return "\n".join(out).rstrip() + "\n"


def write_catalog(settings: Settings, catalogue: Catalogue, path: Path | None = None) -> Path:
    path = path or settings.root / "docs" / "data_catalog.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_catalog(settings, catalogue), encoding="utf-8", newline="\n")
    return path
